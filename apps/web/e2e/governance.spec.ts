import { expect, test } from "@playwright/test";
import { login } from "./helpers";
import type { LabelHubSchema } from "@labelhub/contracts";

test("历史迁移：选择范围、独立审批、真实 worker 与不可变产物", async ({ page, request }) => {
  test.setTimeout(120_000);
  page.setDefaultTimeout(15_000);
  const auth = async (role: string) => {
    const response = await request.post("/api/v1/auth/login", { data: { email: `${role}@labelhub.com`, password: "password123" } });
    expect(response.ok()).toBeTruthy();
    return await response.json() as { token: string; actor: { id: string } };
  };
  const owner = await auth("owner"), reviewer = await auth("reviewer");
  const headers = { Authorization: `Bearer ${owner.token}` };
  const tasksResponse = await request.get("/api/v1/tasks", { headers });
  const tasks = (await tasksResponse.json()).tasks as Array<{ id: string; activeSchemaVersionId?: string }>;
  const task = tasks.find((item) => item.id === "task_demo_news_quality")!;
  expect(task).toBeTruthy();
  const base = `/api/v1/tasks/${task.id}`;
  const sourceResponse = await request.get(`/api/v1/schema-versions/${task.activeSchemaVersionId}`, { headers });
  expect(sourceResponse.ok(), await sourceResponse.text()).toBeTruthy();
  const snapshot = (await sourceResponse.json()).schema as LabelHubSchema;
  const schema = structuredClone(snapshot);
  schema.root.children.push({ id: "migration_check", kind: "FIELD", type: "input.text", name: "migrationCheck", title: "迁移校验", required: false });
  const save = await request.put(`${base}/schema/draft`, { headers, data: { schema } });
  expect(save.ok()).toBeTruthy();
  const published = await request.post(`${base}/schema/publish`, { headers, data: { schemaDraftRevision: (await save.json()).schemaDraftRevision } });
  expect(published.ok(), await published.text()).toBeTruthy();
  const target = (await published.json()).schemaVersion.id as string;
  const candidates = await request.get(`${base}/migration-candidates?schemaVersionId=${task.activeSchemaVersionId}`, { headers });
  expect(candidates.ok(), await candidates.text()).toBeTruthy();
  const submission = (await candidates.json()).items[0] as { id: string };
  expect(submission).toBeTruthy();
  const before = await request.get(`/api/v1/review/submissions/${submission.id}`, { headers: { Authorization: `Bearer ${reviewer.token}` } });
  expect(before.ok(), await before.text()).toBeTruthy();
  const original = (await before.json()).submission;
  expect(original).toBeTruthy();
  const granted = await request.post(`${base}/permissions`, { headers, data: { userId: reviewer.actor.id, actions: ["migration.read", "migration.approve"], effect: "ALLOW" } });
  expect(granted.status()).toBe(201);
  await login(page, "OWNER");
  await page.goto(`/owner/governance?taskId=${task.id}`);
  await page.getByRole("combobox", { name: "源版本", exact: true }).selectOption(task.activeSchemaVersionId!);
  await page.getByRole("combobox", { name: "目标版本", exact: true }).selectOption(target);
  await page.getByRole("checkbox", { name: new RegExp(submission.id) }).check();
  await page.getByLabel("新增字段默认值（JSON）").fill('{"migrationCheck":"迁移核验"}');
  await page.getByRole("button", { name: "创建计划", exact: true }).click();
  const previewResponse = page.waitForResponse((response) => response.url().endsWith("/dry-run") && response.request().method() === "POST");
  await page.getByRole("button", { name: "执行预演", exact: true }).click();
  const preview = await previewResponse;
  expect(preview.ok(), await preview.text()).toBeTruthy();
  expect((await preview.json()).status).toBe("READY");
  await page.getByRole("button", { name: "提交独立审批", exact: true }).click();
  await expect(page.getByRole("button", { name: "批准此摘要" })).toBeVisible();
  const jobs = await request.get(`${base}/migrations`, { headers });
  const job = (await jobs.json()).items[0] as { id: string; checksum: string };
  const denied = await request.post(`${base}/migrations/${job.id}/execute`, { headers, data: {} });
  expect(denied.status()).toBe(409);
  const selfApproval = await request.post(`${base}/migrations/${job.id}/approve`, { headers, data: { checksum: job.checksum, reason: "自批必须拒绝" } });
  expect(selfApproval.status()).toBe(403);
  const approved = await request.post(`${base}/migrations/${job.id}/approve`, { headers: { Authorization: `Bearer ${reviewer.token}` }, data: { checksum: job.checksum, reason: "核对预演与范围" } });
  expect(approved.ok()).toBeTruthy();
  await page.getByRole("button", { name: "刷新权限与状态" }).click();
  await page.getByRole("button", { name: "执行已批准迁移" }).click();
  await expect.poll(async () => {
    const response = await request.get(`${base}/migrations/${job.id}`, { headers });
    return (await response.json()).status;
  }, { timeout: 90_000 }).toBe("SUCCEEDED");
  const records = await request.get(`${base}/migrations/${job.id}/records`, { headers });
  expect((await records.json()).items[0].answers.migrationCheck).toBe("迁移核验");
  const after = await request.get(`/api/v1/review/submissions/${submission.id}`, { headers: { Authorization: `Bearer ${reviewer.token}` } });
  expect((await after.json()).submission).toEqual(original);
});

test("模板运行诊断：真实浏览器加载 Worker、依赖图和追踪", async ({ page }) => {
  await login(page, "OWNER");
  const token = await page.evaluate(() => localStorage.getItem("labelhub_token"));
  const response = await page.request.get("/api/v1/tasks", { headers: { Authorization: `Bearer ${token}` } });
  const task = (await response.json()).tasks.find((entry: { activeSchemaVersionId?: string }) => entry.activeSchemaVersionId);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`/owner/tasks/${task.id}/designer`);
  await page.getByRole("button", { name: "打开运行诊断" }).click();
  await expect(page.getByRole("img", { name: "字段依赖图" })).toBeVisible();
  await expect(page.getByRole("log", { name: "运行追踪" })).toContainText("INITIALIZE");
  await page.getByRole("button", { name: "关闭运行诊断" }).click();
  expect(errors).toEqual([]);
});
